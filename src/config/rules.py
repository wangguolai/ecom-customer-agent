# ═══════════════════════════════════════════════════════════════
# 工具调用「文本泄漏」判据（agent.py 的规则路由纯生成路径用）
# ═══════════════════════════════════════════════════════════════
# 背景（2026-09-20 实测事故，真跑出来的不是推演）：模型想调工具，但那一轮请求**没带 tools**
# （规则路由的纯生成分支刻意省掉决策调用），它只能把调用**写成文本**，而该路径只取 content
# 原样返回 → 用户收到一行 `` `search_products(query="三文鱼 成猫粮")` ``。
# 完整根因链见 docs/routing-leak-fix-plan.md §2/§3。
#
# 实测观察到的三种形态都要覆盖：
#   ① 标识符 + 括号        `search_products(query="...")`      ← 用户实际看到的
#   ② JSON 形             {"name": "search_products", ...}    ← 该次事故的 CoT 原文就是这种
#   ③ 标签形              <tool_call>...
#
# ⚠️ **绝对不能用 `\b`**：Python 正则里中文也算 `\w`，「查search_products(」中 `查` 与 `s`
#    之间**没有词边界**，`\b` 匹配不到 → 检测**静默失效**。这与本文件 ORDER_ID_PATTERN
#    上面记录的「订单20240818001」是**同一个陷阱**，改用负向断言 `(?<![A-Za-z0-9_])`。
#    （早先版本的方案就写错成了 `\b`，被 plan-review 查出。）
_TOOL_CALL_LEAK_RE = re.compile(
    r"(?<![A-Za-z0-9_])[a-z][a-z0-9_]{2,}\s*\("          # ① 小写标识符后紧跟左括号
    # ⚠️ ② 的尾部**也不能用 `\b`**（同一条理由：中文算 `\w`，「tool_calls参数」里
    #    `s` 与 `参` 之间没有词边界 → 漏检）。用负向断言把两侧都锁死。
    r"|(?<![A-Za-z0-9_])tool_calls(?![A-Za-z0-9_])"      # ② JSON 形（键名）
    r"|<tool_call"                                        # ③ 标签形
    # ④ `{"name": "search_products", "arguments": ...}` —— OpenAI tool_calls 的 JSON 形状。
    #    ⚠️ **这条是实测补上的**：最初只写了 ②（匹配 `tool_calls` 键名），而模型实际吐出的
    #    是 `{"name": "search_products", ...}`——**没有 `tool_calls` 这个字面**，直接漏检。
    #    判据写完必须拿真实样本回跑，不能凭"看起来覆盖了"。
    r'|"name"\s*:\s*"[a-z][a-z0-9_]{2,}"'
)


def looks_like_tool_call_leak(text: str) -> bool:
    """文本里是否含工具调用语法（= 模型想调工具但这一轮没给 tools）。

    判据刻意宽松（宁可误判）：宠物电商客服的正常回答里几乎不可能出现「小写英文标识符 + (」，
    误判的代价只是多跑一次生成，不影响正确性。"""
    return bool(text) and _TOOL_CALL_LEAK_RE.search(text) is not None


def strip_tool_call_leak(text: str) -> tuple:
    """剔除含泄漏的行。返回 `(clean_text, leaked)`。

    按**行**剔除：实测泄漏总是独占一行（模型写完过渡话术、换行、再写调用）。
    若调用与正文同行，整行一起丢——随后的重生成会给出完整答案，不会让用户拿到半句话。
    """
    if not looks_like_tool_call_leak(text):
        return text, False
    kept = [ln for ln in text.split("\n") if not _TOOL_CALL_LEAK_RE.search(ln)]
    return "\n".join(kept), True

