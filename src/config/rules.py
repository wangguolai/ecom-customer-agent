#    那边负责渲染、这边负责**白名单校验**（服务端才是权威边界，前端列表只是 UI）。
#    两边漂移的表现是「点得出来但提交被 400」——是可发现的漂移，不是静默失效。
FEEDBACK_REASONS = ("答非所问", "信息错误", "没解决问题", "语气不好", "其他")

# rating 白名单：1 = 好评，-1 = 差评。
# **必须显式枚举而不是 `!= 0` 或区间校验**：写接口的入参只接受「已知合法值」，
# 不是「看起来合理的值」——同 WRITE_TOOLS 白名单的思路。
FEEDBACK_RATINGS = (1, -1)

# trace_id 格式：生成处是 `uuid.uuid4().hex[:16]`（main.py 的 /chat/stream）。
# 校验正则**必须与生成处一致**——否则会出现「系统自己生成的 id 过不了自己的校验」，
# 表现为评分全部 400 且没人知道为什么。
FEEDBACK_TRACE_ID_RE = r"^[0-9a-f]{16}$"

# ═══════════════════════════════════════════════════════════════
# ⚠️ 安全关键：写工具白名单（Prompt Injection 代码级防线）
# ═══════════════════════════════════════════════════════════════
# 读/写分离：写工具的行为在代码层被约束，不随 LLM 意图走——LLM 说要给用户退款，
# 也得先过这里的权限门槛。改动本项 = 改动安全边界，必须过 code review。
WRITE_TOOLS = {"refund_order", "transfer_to_human"}

# ═══════════════════════════════════════════════════════════════
# 退款工单状态机（模块 5）
# ═══════════════════════════════════════════════════════════════
# pending → approved → refunded（终态）；pending → rejected（终态）。
# 状态流转由代码层/人工驱动（审批接口），**不由 LLM 驱动**——这是「写操作不能由模型说了算」的落地。
# 终态（refunded/rejected）不在任何 {当前状态} 里 → 任何 action 都非法（终态不可再流转）。
REFUND_STATUS_PENDING = "待人工审批"
REFUND_STATUS_APPROVED = "已批准"
REFUND_STATUS_REFUNDED = "已退款"
REFUND_STATUS_REJECTED = "已拒绝"

# 合法流转表：action → {当前状态: 新状态}。只有匹配的当前状态才允许该 action。
REFUND_TRANSITIONS = {
    "approve": {REFUND_STATUS_PENDING: REFUND_STATUS_APPROVED},
    "execute": {REFUND_STATUS_APPROVED: REFUND_STATUS_REFUNDED},
    "reject": {REFUND_STATUS_PENDING: REFUND_STATUS_REJECTED},
}

# ═══════════════════════════════════════════════════════════════
# ⚠️ 安全关键：出网白名单（Prompt Injection 架构级防御）
# ═══════════════════════════════════════════════════════════════
# 只允许访问本机 + compose 服务名。真实部署用 EGRESS_EXTRA_HOSTS 显式追加——
# 「显式追加」和「默认放行任意 host」是两回事。改动本项 = 改动安全边界。
EGRESS_DEFAULT_HOSTS = {"localhost", "127.0.0.1", "::1", "backend"}
EGRESS_ALLOWED_SCHEMES = {"http", "https"}
