MAX_TOOL_CALLS_PER_TURN = 5      # 单次 LLM 决策最多返回的工具调用数，超了直接让用户收敛（防一次狂调一堆工具）
MAX_TOOL_RESULT_LEN = 500        # 单个工具结果的字符截断上限（防 Token 爆炸）
MAX_OUTPUT_TOKENS = 2048         # 面向用户的 LLM 生成输出上限（纯兜底：防失控/封顶成本，不是「长度控制器」，简洁靠 prompt 约束）
