MODEL_TIER_DECISION = "deep"
"""ReAct **决策轮**（选工具 / 判断是否收敛）用哪一档。表达类与机械类固定走打底档（fast）。

**为什么不把决策也降到 fast**——实测（2026-09-20，同一句多步 query，跑两次取一致结论）：
  · 全 pro     4 步 / 9.87s，`search_products` 调 **2 次**
  · 全 flash   4 步 / 8.2-8.6s，`search_products` 调 **4-5 次**
flash 确实更快，但它**更容易「结果不满意就再搜一次」**——工具调用次数翻倍是可观测的
行为退化（成本翻倍，且答案可能被后面那次搜索结果带偏）。
**没有评测数据证明这种退化不影响最终答案之前，判断类调用留在强模型上**——
与项目「宁可漏不可错」的取向一致。

⚠️ **刻意不做「按步数闪切模型」**（同一循环里前几步 fast、后几步 deep）：实测**有害**——
  · flash 起 + pro 升：**7 步 / 11.37s**，`search_products` 调 5 次（三组里最差）
闪切反而步数最多，推测是同一循环里换模型让上下文里的「决策风格」突变。
正确方向是「按**失败信号**升级」（工具返回空 / 同工具连调 / 检索双低），
但那要先攒够打底档的失败样本才谈得上定阈值——**没样本就调阈值是猜**。
"""

# ── LLM 推理强度（思考模式）─────────────────────────────────────
# DeepSeek-V4 系列**默认开启思考模式、默认 effort=high**（官方文档），即：不传这个
# 参数就是 high。2026-09-20 实测（长句 query，114 字）：
#   · 不传（=high）：reasoning 2832 token、首 token **29.6s**、答案 358 字符
#   · "low"        ：reasoning  232 token、首 token **3.2s**、答案 321 字符（-10%）
#   · 关闭思考      ：reasoning    0 token、首 token **0.98s**、答案 **62 字符**（塌了）
# 推理 token 当时占 completion 的 **99%** —— 客服场景（查订单/政策/推荐）不需要
# 几千 token 的推理，延迟却全压在推理段（用户面对白屏）。
#
# ⚠️ 取值 **None / "low" / "high" / "max"**。None = 不传该参数（服务端默认）。
#    **不要写 "medium" / "xhigh"**：官方映射表里它们都落到 high，写了等于没写。
#
# ⚠️ 思考模式下 `temperature` / `top_p` **不生效**（官方文档：设置不报错也不生效）。
#    所以本项非 None 时，llm.py 传的 temperature=0.0 是个**空操作**——这是思考模式的
#    既定行为不是 bug，别去"修"它；也意味着「换模型/关思考」会让 temperature 突然开始
#    生效，届时输出稳定性会变，必须重跑评测。
#
# ⚠️ 默认刻意留 None（=现状）而不是直接改 low：**先不改变行为，等 A/B 评测数据说话**。
#
# ⚠️ **`"off"` 刻意不在本项取值域内**——它只允许按调用点显式传（见下面
#    REASONING_EFFORT_MECHANICAL）。理由：全局关思考会让**主循环**也失去推理，而实测
#    「关闭思考 → 长句答案从 358 字符塌到 62 字符」（见上面的实测表）。机械任务关，
#    主循环不开——两者风险完全不同，不能共用一个旋钮。
REASONING_EFFORT = None

# 机械任务（上下文压缩 / 画像抽取）专用的推理强度：**关闭思考**。
#
# 为什么必须关（2026-09-20 实测，线上功能失效级）：
#   推理 token **计入 `completion_tokens`**，而 `max_tokens` 封顶的正是 `completion_tokens`。
#   这两个调用的小预算是为「输出一条摘要 / 一个 JSON」设的，结果被推理整段吃光：
#     摘要  max_tokens=300 → completion=300, reasoning=300, content=''   ← 一个字都没有
#     抽取  max_tokens=400 → completion=400, reasoning=400, content=''
#   摘要为空 → agent 的空摘要守卫触发 → **压缩从未生效，历史无限膨胀（Token 爆炸）**；
#   抽取为空 → **用户画像从未被自动写入过**。两条路径都只打一行几乎没人看见的警告。
#   关掉思考后：摘要 completion=60、抽取 completion=68，正文正常产出。
#
# ⚠️ 「关思考」和「调低强度」是两回事，别混：
#   · `"off"`  → reasoning=0，正文必出。机械任务要的是这个。
#   · `"low"`  → 仍是思考模式（实测 reasoning 仍有 232~278），`temperature=0.0` **依旧空操作**。
#     实测 `low` + 预算 600 也能出摘要，但 completion 327 vs `off` 的 60 —— 贵 5.5 倍。
REASONING_EFFORT_MECHANICAL = "off"

